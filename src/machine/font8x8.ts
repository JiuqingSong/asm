function boxGlyph([u, d, l, r]: [number, number, number, number]): number[] {
  const px = Array.from({ length: 8 }, () => new Array(8).fill(0));
  const lines = (s: number) => (s === 2 ? [2, 4] : [3]);
  const vs = Math.max(u, d), hs = Math.max(l, r);
  for (const x of lines(vs)) {
    if (u) for (let y = 0; y <= (hs === 2 ? 4 : 3); y++) px[y][x] = 1;
    if (d) for (let y = hs === 2 ? 2 : 3; y < 8; y++) px[y][x] = 1;
  }
  for (const y of lines(hs)) {
    if (l) for (let x = 0; x <= (vs === 2 ? 4 : 3); x++) px[y][x] = 1;
    if (r) for (let x = vs === 2 ? 2 : 3; x < 8; x++) px[y][x] = 1;
  }
  return px.map(row => row.reduce((b, v, i) => b | (v << (7 - i)), 0));
}

