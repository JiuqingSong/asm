/** 内置字库里有字形的字符（其余的由界面补上） */
export function hasBuiltinGlyph(ch: number): boolean {
  return (ch >= 0x20 && ch < 0x7f) || ch === 0 || BOX[ch] !== undefined || BLOCKS[ch] !== undefined;
}

export function builtinFont(): Uint8Array {
  const font = new Uint8Array(2048);
  for (const [c, rows] of Object.entries(ASCII)) {
    const ch = c.charCodeAt(0);
    rows.forEach((v, y) => { font[ch * 8 + y] = (v & 31) << 2; });
  }
  for (const [ch, dirs] of Object.entries(BOX)) font.set(boxGlyph(dirs), +ch * 8);
  for (const [ch, rows] of Object.entries(BLOCKS)) font.set(rows, +ch * 8);
  return font;
}
