; 完整段定义风格（老教材）
DATA SEGMENT
  BUF   DB 20, ?, 20 DUP(?)
  TAB   DW 1, 2, 3, 4
  N     EQU 4
  STR1  DB "ABC", 0
  CNT   = 3
  CNT   = CNT + 1
  PTRS  DW TAB, STR1
  NEST  DB 2 DUP(1, 2 DUP(7)), 0FFh
  LEN   EQU $ - STR1
DATA ENDS

STACK1 SEGMENT STACK
  DW 64 DUP(0)
STACK1 ENDS

CODE SEGMENT
  ASSUME CS:CODE, DS:DATA, SS:STACK1
START:
  MOV AX, DATA
  MOV DS, AX
  MOV CX, N
  MOV CX, CNT
  MOV CX, LEN
  MOV SI, OFFSET TAB
  MOV AX, TAB[SI]
  MOV BX, TYPE TAB
  MOV BX, LENGTH TAB
  MOV BX, SIZE TAB
  MOV BX, LENGTHOF TAB
  MOV BX, SIZEOF TAB
  MOV BX, LENGTH BUF+2
  MOV AL, BUF+1
  MOV DL, 'A'
  MOV AX, 'AB'
  MOV AL, N * 2 + 1
  MOV AL, -1
  MOV AX, NOT 0
  MOV AX, 1 SHL 4
  MOV AL, HIGH 1234H
  MOV AL, LOW 1234H
  MOV AX, 10 MOD 3
  MOV AX, (N + 1) * 2
  MOV AX, SEG TAB
  MOV AH, 4CH
  INT 21H
CODE ENDS
  END START
