import { existsSync, readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { spawnSync } from 'node:child_process';

const root = resolve(import.meta.dirname, '..');
const source = join(root, 'vendor', 'softfloat', 'source');
const compiler = process.env.ZIG || 'zig';
const temp = mkdtempSync(join(tmpdir(), 'asm86-softfloat-'));
try {
  const output = join(temp, 'softfloat.wasm');
  const manifest = readFileSync(join(root, 'vendor', 'softfloat', 'Makefile'), 'utf8');
  const files = [...manifest.matchAll(/^\s+(\w+)\$\(OBJ\)/gm)].map(([, name]) => {
    const specialized = join(source, '8086', name + '.c');
    return existsSync(specialized) ? specialized : join(source, name + '.c');
  });
  const args = ['-target', 'wasm32-freestanding', '-O2', '-flto', '-nostdlib',
    '-DSOFTFLOAT_FAST_INT64', '-DINLINE_LEVEL=5', '-DSOFTFLOAT_FAST_DIV32TO16', '-DSOFTFLOAT_FAST_DIV64TO32',
    '-I' + join(root, 'tools', 'softfloat'), '-I' + join(source, '8086'), '-I' + join(source, 'include'),
    ...files, join(root, 'tools', 'softfloat', 'kernel.c'),
    '-Wl,--no-entry', '-Wl,--export=calculate', '-Wl,--export=get_buffer',
    '-Wl,--export-memory', '-Wl,-z,stack-size=32768',
    '-Wl,--initial-memory=131072', '-Wl,--max-memory=131072', '-o', output];
  const response = join(temp, 'args.rsp');
  writeFileSync(response, args.map(arg => JSON.stringify(arg)).join('\n'));
  const result = spawnSync(compiler, ['cc', '@' + response], { stdio: 'inherit' });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error('SoftFloat compilation failed: ' + result.status);
  const bytes = readFileSync(output);
  const sha256 = (await import('node:crypto')).createHash('sha256').update(bytes).digest('hex');
  writeFileSync(join(root, 'src', 'cpu', 'softfloat-wasm.ts'),
    '// Generated by npm run build:softfloat from Berkeley SoftFloat 3e. Do not edit.\n' +
    '// License: vendor/softfloat/COPYING.txt. WASM SHA256: ' + sha256 + '\n' +
    'export const softfloatWasm = \'' + bytes.toString('base64') + '\';\n');
  console.log(`SoftFloat: ${bytes.length} bytes, SHA256 ${sha256}`);
} finally {
  rmSync(temp, { recursive: true, force: true });
}
